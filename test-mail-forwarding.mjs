import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const c = vm.createContext({ Date, console });
vm.runInContext(fs.readFileSync(new URL('./apps-script/Code.gs', import.meta.url), 'utf8'), c);
const body = 'Od: Jarosław Dymek <dymek.jaroslaw@mowmalbork.pl>\nDate: 2026-09-15\n\nOd: Dariusz Górski <dariusz.gorski@mowmalbork.pl>\nDate: pt., 11 wrz 2026 o 15:10\nPozdrawiam';
const message = sender => ({ getFrom: () => sender, getPlainBody: () => body, getDate: () => new Date('2026-09-15T09:48:00') });
assert.equal(c.resolveDirectorMessage_(message('other@example.org')), null);
const forwarded = c.resolveDirectorMessage_(message('Jarosław Dymek <dymek.jaroslaw@mowmalbork.pl>'));
assert.equal(forwarded.date.getDate(), 11);
assert.equal(forwarded.date.getHours(), 15);
assert.ok(c.resolveDirectorMessage_(message('Dariusz Górski <dariusz.gorski@mowmalbork.pl>')));
assert.equal(c.resolveDirectorMessage_({ ...message('dymek.jaroslaw@mowmalbork.pl'), getPlainBody: () => 'Kontakt: dariusz.gorski@mowmalbork.pl' }), null);
const older = { source: { priority: 100, messageDate: '2026-09-10', kind: 'correction-gr6' }, rawText: 'older' };
const newer = { source: { priority: 96, messageDate: '2026-09-11', kind: 'correction-internat' }, rawText: 'newer' };
assert.ok(c.compareDocs_(newer, older) < 0);
c.parseInternatSchedule_ = text => ({ totalHours: text === 'newer' ? 0 : 8, days: [] });
const selected = c.chooseBestPlanForEducator_([older, newer], '2026-09-14', 'Dymek');
assert.equal(selected.doc, newer);
assert.equal(selected.parsed.totalHours, 0);
console.log('OK: exact sender, nested forwarding, original date, correction priority and no stale fallback.');
